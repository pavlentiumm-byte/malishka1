function runCastingTests() {
  const day=offsetDay(7),future=offsetDay(8),today=shootDateKey();
  const data={title:'Portrait',description:'Concept',city:'City',location:'Studio',genre:'Portrait',author:'Author',date:day,time:'12:30',format:'paid',budget:'1000.50',deadline:today};
  const roles=[{name:'Model',count:1},{name:'Makeup',count:2}];
  assert(validateCasting(data,roles)==='','valid full announcement');
  assert(validateCasting({...data,budget:'-1'},roles),'negative payment rejected');
  assert(validateCasting({...data,budget:'1.001'},roles),'excess precision rejected');
  assert(validateCasting({...data,date:'2027-02-30'},roles),'impossible date rejected');
  assert(validateCasting({...data,deadline:future},roles),'deadline after shoot rejected');
  assert(validateCasting({...data,time:'24:00'},roles),'invalid time rejected');
  assert(validateCasting(data,[...roles,{name:' model ',count:1}]),'duplicate roles rejected');
  assert(validateCasting(data,[{name:'Model',count:1.5}]),'fractional slots rejected');
  assert(validateCasting({...data,format:'discuss',budget:''},roles)==='','discuss format needs no budget');
  assert(paidFormat('discuss')==='discuss'&&paidFormat('Оплата')==='paid'&&paidFormat('TFP')==='TFP','legacy and new formats');
  const record={...data,id:'casting-test',roles,responses:[{id:'a',personId:1,role:'Model',status:'pending'},{id:'b',personId:2,role:'Model',status:'invited'}],customLegacyField:'keep'};
  assert(workflowSave('castings',[record]),'seed original key');
  assert(!changeCastingResponse(record.id,'a','accepted'),'cannot accept without invitation');
  assert(changeCastingResponse(record.id,'a','invited'),'invite');
  assert(changeCastingResponse(record.id,'a','accepted'),'accept');
  assert(!changeCastingResponse(record.id,'b','accepted'),'capacity rejects second accepted participant');
  assert(castingSnapshot().items[0].customLegacyField==='keep','unknown old fields preserved');
  assert(changeCastingResponse(record.id,'a','declined'),'decline releases slot');
  assert(changeCastingResponse(record.id,'b','accepted'),'released slot can be filled');
  assert(updateCasting(record.id,p=>({...p,closed:true})),'close');
  assert(!changeCastingResponse(record.id,'a','invited'),'closed announcement cannot invite');
  assert(updateCasting(record.id,p=>({...p,closed:false})),'reopen');
  assert(filterCastings([record],{role:'make',genre:'port',format:'paid',scope:'active'},today).length===1,'multi-role genre filtering');
  assert(filterCastings([{...record,deadline:'2000-01-01'}],{scope:'active'},today).length===0,'past deadline hidden from active');
  assert(castingRoles({role:'Old role'})[0].count===1,'old roles compatible');
  const stale=castingSnapshot();updateCasting(record.id,p=>({...p,title:'New'}));
  assert(!saveCastingSnapshot(stale,[]),'stale snapshot cannot overwrite newer data');
  const stored=memory['kadr-html-castings'];storageFails=true;
  assert(!updateCasting(record.id,p=>({...p,title:'Lost'})),'quota returns failure');
  assert(memory['kadr-html-castings']===stored,'quota preserves original');storageFails=false;
  memory['kadr-html-castings']='{broken';
  assert(castingSnapshot().error,'corruption exposed');assert(!updateCasting(record.id,p=>p),'corrupt storage blocks changes');
  assert(memory['kadr-html-castings']==='{broken','corruption never overwritten');
  memory['kadr-html-castings']='{}';assert(castingSnapshot().error,'non-array rejected');
  memory['kadr-html-castings']=stored;
  assert(castingSnapshot().items[0].responses[1].status==='accepted','serialized response state restored');
}
